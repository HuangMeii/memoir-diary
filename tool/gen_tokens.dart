// Reads DTCG design tokens (tokens/ + tokens.resolver.json) and generates
// flutter_app/lib/src/ui/tokens.dart. Run from the repository root:
//
//   dart run tool/gen_tokens.dart
import 'dart:convert';
import 'dart:io';

String camel(String raw) {
  final parts = raw.split(RegExp(r'[^A-Za-z0-9]+')).where((p) => p.isNotEmpty);
  if (parts.isEmpty) return '';
  final head = parts.first.toLowerCase();
  final tail = parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1));
  return [head, ...tail].join();
}

List<String> refsOf(dynamic node) {
  final list = (node is Map ? node['sources'] : node) as List;
  return list.map((e) => ((e as Map)['\$ref'] as String)).toList();
}

Map<String, dynamic> readJson(String path) =>
    jsonDecode(File(path).readAsStringSync()) as Map<String, dynamic>;

Map<String, dynamic> readRefs(String dir, List<String> files) {
  final out = <String, dynamic>{};
  for (final f in files) {
    out.addAll(readJson('$dir/$f'));
  }
  return out;
}

Map<String, dynamic> pickSet(Map<String, dynamic> doc, String needle) {
  for (final e in doc.entries) {
    if (e.value is Map && e.key.contains(needle)) return e.value as Map<String, dynamic>;
  }
  return <String, dynamic>{};
}

void flatten(Map<String, dynamic> node, String prefix, Map<String, Map<String, dynamic>> out) {
  for (final e in node.entries) {
    if (e.key.startsWith('\$')) continue;
    final v = e.value;
    if (v is! Map<String, dynamic>) continue;
    final path = prefix.isEmpty ? e.key : '$prefix.${e.key}';
    if (v.containsKey('\$value')) {
      out[path] = v;
    } else {
      flatten(v, path, out);
    }
  }
}

String? colorExpr(Map<String, dynamic> token) {
  final value = token['\$value'];
  if (value is! Map) return null;
  final hex = (value['hex'] as String).replaceFirst('#', '');
  final r = int.parse(hex.substring(0, 2), radix: 16);
  final g = int.parse(hex.substring(2, 4), radix: 16);
  final b = int.parse(hex.substring(4, 6), radix: 16);
  final alpha = value['alpha'];
  if (alpha == null) {
    final argb = (0xFF << 24) | (r << 16) | (g << 8) | b;
    return 'Color(0x${argb.toRadixString(16).toUpperCase().padLeft(8, '0')})';
  }
  return 'Color.fromARGB(${((alpha as num) * 255).round()}, $r, $g, $b)';
}

String numLiteral(String raw, Map<String, Map<String, dynamic>> source) {
  final t = raw.trim();
  if (!t.startsWith('{')) return t;
  final path = t.replaceAll(RegExp(r'^\{|\}$'), '').split('.').skip(1).join('.');
  final token = source[path];
  final v = token?['\$value'];
  if (v is num) return v % 1 == 0 ? v.toInt().toString() : v.toString();
  if (v is String) return numLiteral(v, source);
  return t;
}

void main() {
  final dir = '${Directory.current.path}/tokens';
  final resolver = readJson('$dir/tokens.resolver.json');

  final foundationDoc = readRefs(
    dir,
    refsOf((resolver['sets'] as Map)['memoir-foundation']),
  );
  final foundation = <String, Map<String, dynamic>>{};
  flatten(pickSet(foundationDoc, 'Foundation'), '', foundation);

  final contexts = ((resolver['modifiers'] as Map)['memoir-colors'] as Map)['contexts'] as Map;
  final palettes = <String, Map<String, Map<String, dynamic>>>{};
  contexts.forEach((mode, node) {
    final flat = <String, Map<String, dynamic>>{};
    flatten(pickSet(readRefs(dir, refsOf(node)), 'Colors'), '', flat);
    palettes[mode as String] = flat;
  });

  final buf = StringBuffer()
    ..writeln('// GENERATED by tool/gen_tokens.dart from tokens/. Do not edit by hand.')
    ..writeln('// ignore_for_file: unused_field')
    ..writeln()
    ..writeln("import 'package:flutter/material.dart';")
    ..writeln();

  palettes.forEach((mode, flat) {
    buf.writeln('/// Palette for the $mode mode (tokens/memoir-colors-${mode.toLowerCase()}).');
    buf.writeln('abstract final class MemoirColors$mode {');
    final keys = flat.keys.toList()..sort();
    for (final k in keys) {
      final expr = colorExpr(flat[k]!);
      if (expr == null) continue;
      buf.writeln('  static const Color ${camel(k)} = $expr;');
    }
    buf.writeln('}');
    buf.writeln();
  });

  void numbers(String group, String className, Map<String, Map<String, dynamic>> src,
      {String? strip}) {
    buf.writeln('/// $group tokens (tokens/memoir-foundation.tokens.json).');
    buf.writeln('abstract final class $className {');
    final base = strip == null ? '' : '$strip.';
    final keys = src.keys.where((k) => k.startsWith(base)).toList()..sort();
    for (final k in keys) {
      var name = camel(strip == null ? k : k.substring(base.length));
      if (RegExp(r'^\d').hasMatch(name)) name = 's$name';
      final v = src[k]!['\$value'];
      final literal = v is num ? (v % 1 == 0 ? v.toInt().toString() : v.toString()) : numLiteral('$v', src);
      buf.writeln('  static const double $name = $literal;');
    }
    buf.writeln('}');
    buf.writeln();
  }

  numbers('Type scale', 'MemoirType', foundation, strip: 'type');
  numbers('Spacing', 'MemoirSpace', foundation, strip: 'space');
  numbers('Corner radius', 'MemoirRadius', foundation, strip: 'radius');

  final out = File('${Directory.current.path}/flutter_app/lib/src/ui/tokens.dart');
  out.writeAsStringSync(buf.toString());
  stdout.writeln('wrote ${out.path}');
}
